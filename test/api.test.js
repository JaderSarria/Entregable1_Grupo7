const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');

test('CRUD, imágenes, credenciales, errores y persistencia', async t => {
  const testRoot = process.env.TEST_TMP_DIR || os.tmpdir();
  await fs.mkdir(testRoot, { recursive: true });
  const temp = await fs.mkdtemp(path.join(testRoot, 'entregable-'));
  process.env.DATA_DIR = path.join(temp, 'data');
  process.env.PUBLIC_DIR = path.join(temp, 'public');
  await fs.cp(path.join(__dirname, '../public'), process.env.PUBLIC_DIR, { recursive: true });
  const { app, initialize } = require('../src/app');
  const { verifyPassword } = require('../src/utils/crypto');
  await initialize();
  const inProcess = process.env.TEST_IN_PROCESS === '1';
  const server = inProcess ? null : app.listen(0, '127.0.0.1');
  if (server) await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => {
    if (server) await new Promise(resolve => server.close(resolve));
    await fs.rm(temp, { recursive: true, force: true });
  });
  const base = server ? `http://127.0.0.1:${server.address().port}` : 'http://localhost';
  const transport = inProcess ? (url, options) => require('./helpers/in-process.cjs')(app, url, options) : fetch;
  const request = async (url, method = 'GET', body) => {
    const response = await transport(base + url, { method, body: body instanceof FormData ? body : body === undefined ? undefined : JSON.stringify(body), headers: body && !(body instanceof FormData) ? { 'Content-Type': 'application/json' } : {} });
    return { status: response.status, body: await response.json() };
  };
  let checks = 0;
  const status = (actual, expected) => { assert.equal(actual.status, expected); checks++; };
  const home = await transport(base + '/');
  status(home, 200);
  assert.match(await home.text(), /id="record-form"/);
  for (const asset of ['/app.js', '/styles.css', '/favicon.svg']) status(await transport(base + asset), 200);
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aL1sAAAAASUVORK5CYII=', 'base64');
  const form = (fields, field, count = 1) => {
    const data = new FormData();
    for (const [key, value] of Object.entries(fields)) data.append(key, value);
    for (let i = 0; i < count; i++) data.append(field, new Blob([png], { type: 'image/png' }), 'image.png');
    return data;
  };
  status(await request('/api/users'), 200);
  status(await request('/api/users', 'POST', {}), 400);
  const fields = { firstname: 'Ana', lastname: 'Pérez', username: 'ana', password: 'clave segura' };
  const user = await request('/api/users', 'POST', form(fields, 'avatar'));
  status(user, 201); assert.equal(user.body.password, undefined);
  const uid = user.body.id;
  assert.equal((await transport(base + user.body.avatar)).status, 200); checks++;
  let stored = JSON.parse(await fs.readFile(path.join(process.env.DATA_DIR, 'users.json'), 'utf8'));
  assert.ok(await verifyPassword(fields.password, stored[0].password)); checks++;
  status(await request('/api/users', 'POST', fields), 400);
  status(await request(`/api/users/${uid}`), 200);
  const updated = await request(`/api/users/${uid}`, 'PUT', form({ password: 'nueva clave' }, 'avatar'));
  status(updated, 200);
  assert.equal((await transport(base + user.body.avatar)).status, 404); checks++;
  stored = JSON.parse(await fs.readFile(path.join(process.env.DATA_DIR, 'users.json'), 'utf8'));
  assert.ok(await verifyPassword('nueva clave', stored[0].password)); checks++;
  assert.ok(!(await request('/api/users')).body.some(item => 'password' in item)); checks++;
  const petFields = { especie: 'perro', color: 'negro', edad: '4', sexo: 'macho' };
  const pet = await request('/api/pets', 'POST', form(petFields, 'img', 5));
  status(pet, 201); assert.equal(pet.body.img.length, 5); assert.equal(pet.body.edad, 4);
  const pid = pet.body.id;
  for (const url of pet.body.img) { assert.equal((await transport(base + url)).status, 200); checks++; }
  status(await request('/api/pets'), 200);
  status(await request(`/api/pets/${pid}`), 200);
  status(await request('/api/pets', 'POST', form(petFields, 'img', 6)), 400);
  status(await request('/api/pets', 'POST', { ...petFields, edad: -1 }), 400);
  status(await request('/api/pets', 'POST', { ...petFields, sexo: 'otro' }), 400);
  const appended = await request(`/api/pets/${pid}`, 'PUT', form({ color: 'blanco' }, 'img'));
  status(appended, 200); assert.equal(appended.body.img.length, 6);
  const replaced = await request(`/api/pets/${pid}`, 'PUT', form({ imageMode: 'replace' }, 'img'));
  status(replaced, 200); assert.equal(replaced.body.img.length, 1);
  assert.equal((await transport(base + pet.body.img[0])).status, 404); checks++;
  await initialize();
  assert.equal((await request(`/api/pets/${pid}`)).body.color, 'blanco'); checks++;
  status(await request('/api/users/no-id'), 400);
  status(await request('/api/users/99999'), 404);
  status(await request('/api/pets/99999', 'PUT', { color: 'gris' }), 404);
  status(await request('/api/pets/99999', 'DELETE'), 404);
  const wrong = new FormData(); wrong.append('avatar', new Blob(['hola'], { type: 'text/plain' }), 'x.txt');
  status(await request('/api/users', 'POST', wrong), 400);
  status(await request(`/api/users/${uid}`, 'DELETE'), 200);
  status(await request(`/api/pets/${pid}`, 'DELETE'), 200);
  status(await request(`/api/users/${uid}`), 404);
  status(await request(`/api/pets/${pid}`), 404);
  status(await request('/inexistente'), 404);
  const dataPath = path.join(process.env.DATA_DIR, 'pets.json');
  await fs.writeFile(dataPath, 'invalid JSON');
  status(await request('/api/pets'), 500);
  await fs.writeFile(dataPath, '[]');
  const concurrent = await Promise.all(Array.from({ length: 8 }, () => request('/api/pets', 'POST', petFields)));
  assert.ok(concurrent.every(result => result.status === 201));
  assert.equal(new Set(concurrent.map(result => result.body.id)).size, 8);
  assert.equal((await request('/api/pets')).body.length, 8); checks++;
  console.log(`${checks} comprobaciones de API, interfaz estática, archivos y seguridad superadas (${inProcess ? 'Express en proceso, sin red' : 'HTTP real'})`);
});
